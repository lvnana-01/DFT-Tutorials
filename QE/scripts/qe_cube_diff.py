#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
qe_cube_diff.py -- charge-density difference and planar averages with Gaussian cube files.
                   cube 文件工具：差分电荷 drho = rho(AB) - rho(A) - rho(B)（任意线性组合），
                   沿某一晶轴的平面平均与累积电荷 Delta Q(z)，以及积分与基本信息。

Part of DFT-Tutorials (https://github.com/zenggs05/DFT-Tutorials) - MIT License

Typical QE workflow (chapter 10)
  pw.x scf for AB, A and B with the SAME cell, ecutwfc/ecutrho (=> same FFT grid) and atoms
  of A and B at the same positions as in AB; then for each:
     pp.x  &INPUTPP prefix=..., outdir=..., plot_num=0, filplot='ab.rho' /
           &PLOT iflag=3, output_format=6, fileout='ab_rho.cube' /
  then
     python qe_cube_diff.py diff drho.cube ab_rho.cube a_rho.cube b_rho.cube
     python qe_cube_diff.py planar drho.cube --axis 3 -o drho_z.png
Cube format (Gaussian): 2 comment lines; "natoms x0 y0 z0"; three "N_i  v_ix v_iy v_iz"
  lines (bohr if N_i > 0); natoms lines "Z  q  x y z"; data with the third index fastest.
  integral = sum(values) * dV (voxel volume, bohr^3).  For a pp.x plot_num=0 cube this
  should equal the number of valence electrons - check it once with "info" before
  interpreting differences (the planar profile below assumes density units e/bohr^3).

Sub-commands
  info   CUBE ...                     grid, cell, value range, integral
  diff   OUT A B [C ...] [--coeffs 1 -1 -1]   OUT = sum c_i * input_i (default 1, -1, -1, ...)
  planar CUBE [--axis 3] [--csv F] [-o F]   plane average rho(z) (e/bohr^3 -> e/A per unit z),
                                            charge per unit length lambda(z) = int rho dxdy
                                            and Delta Q(z) = int_0^z lambda dz'

Usage examples
--------------
    python qe_cube_diff.py info ab_rho.cube
    python qe_cube_diff.py diff drho.cube ab_rho.cube a_rho.cube b_rho.cube
    python qe_cube_diff.py diff spin.cube up.cube dn.cube --coeffs 1 -1
    python qe_cube_diff.py planar drho.cube --axis 3 --csv drho_z.csv -o drho_z.png

Dependencies: python >= 3.9, numpy; matplotlib only for planar -o (Agg unless --show).
"""
import argparse
import sys

BOHR_A = 0.529177210903


class Cube:
    def __init__(self, path):
        import numpy as np
        self.path = path
        with open(path) as fh:
            self.comments = [fh.readline().rstrip("\n"), fh.readline().rstrip("\n")]
            v = fh.readline().split()
            self.nat = int(v[0])
            self.origin = [float(x) for x in v[1:4]]
            self.extra = v[4:]
            self.n, self.vec = [], []
            for _ in range(3):
                v = fh.readline().split()
                self.n.append(int(v[0]))
                self.vec.append([float(x) for x in v[1:4]])
            self.atoms = [fh.readline().rstrip("\n") for _ in range(abs(self.nat))]
            if self.nat < 0:  # orbital cube: one extra line with orbital indices
                self.atoms.append(fh.readline().rstrip("\n"))
            data = np.array(fh.read().split(), dtype=float)
        if any(k < 0 for k in self.n):
            self.unit = "angstrom"
            self.n = [abs(k) for k in self.n]
        else:
            self.unit = "bohr"
        if data.size != self.n[0] * self.n[1] * self.n[2]:
            sys.exit("%s: data size %d != %d x %d x %d" % (path, data.size, *self.n))
        self.data = data.reshape(self.n)

    @property
    def dv(self):
        import numpy as np
        return abs(float(np.linalg.det(np.array(self.vec))))  # voxel volume (unit^3)

    def write(self, path, data, comment):
        with open(path, "w", newline="\n") as fh:
            fh.write(comment[:80] + "\n")
            fh.write("generated by qe_cube_diff.py\n")
            fh.write("%5d %12.6f %12.6f %12.6f%s\n" % (self.nat, *self.origin,
                                                     "".join(" " + e for e in self.extra)))
            for k in range(3):
                nk = self.n[k] if self.unit == "bohr" else -self.n[k]
                fh.write("%5d %12.6f %12.6f %12.6f\n" % (nk, *self.vec[k]))
            for a in self.atoms:
                fh.write(a + "\n")
            flat = data.reshape(self.n[0] * self.n[1], self.n[2])
            for row in flat:
                for i in range(0, len(row), 6):
                    fh.write(" ".join("%13.5E" % x for x in row[i:i + 6]) + "\n")


def info(args):
    for f in args.cubes:
        c = Cube(f)
        tot = c.data.sum() * c.dv
        print("== %s" % f)
        print("   comment : %s | %s" % (c.comments[0].strip(), c.comments[1].strip()))
        print("   atoms %d, grid %d x %d x %d, lengths in %s" % (abs(c.nat), *c.n, c.unit))
        for k in range(3):
            print("   a%d = %s (%d x voxel)" % (k + 1, " ".join("%.5f" % (x * c.n[k]) for x in c.vec[k]),
                                             c.n[k]))
        print("   min %.5e  max %.5e  integral %.5f (positive %.5f, negative %.5f)"
              % (c.data.min(), c.data.max(), tot, c.data[c.data > 0].sum() * c.dv,
                 c.data[c.data < 0].sum() * c.dv))


def same_grid(a, b, tol=1e-4):
    import numpy as np
    return a.n == b.n and np.allclose(a.vec, b.vec, atol=tol) and np.allclose(a.origin, b.origin, atol=tol)


def diff(args):
    cubes = [Cube(f) for f in args.inputs]
    coeffs = args.coeffs or ([1.0] + [-1.0] * (len(cubes) - 1))
    if len(coeffs) != len(cubes):
        sys.exit("%d coefficients for %d cubes" % (len(coeffs), len(cubes)))
    for c in cubes[1:]:
        if not same_grid(cubes[0], c):
            sys.exit("grid/cell of %s differs from %s: use the same cell and ecutrho "
                     "(or set nr1/nr2/nr3) in all pw.x runs" % (c.path, cubes[0].path))
    out = sum(k * c.data for k, c in zip(coeffs, cubes))
    expr = " ".join("%+g*%s" % (k, c.path) for k, c in zip(coeffs, cubes))
    cubes[0].write(args.output, out, "difference: " + expr)
    dv = cubes[0].dv
    print("wrote %s = %s" % (args.output, expr))
    print("integral %.5f e (should be ~0 for rho_AB - rho_A - rho_B), positive %.5f, negative %.5f"
          % (out.sum() * dv, out[out > 0].sum() * dv, out[out < 0].sum() * dv))
    print("NOTE: the atoms written are those of %s" % cubes[0].path)


def planar(args):
    import numpy as np
    c = Cube(args.cube)
    ax = args.axis - 1
    others = tuple(i for i in range(3) if i != ax)
    prof = c.data.mean(axis=others)                      # e/bohr^3 (average over plane)
    to_a = BOHR_A if c.unit == "bohr" else 1.0
    vec = np.array(c.vec)
    vol = c.dv * c.n[0] * c.n[1] * c.n[2]
    length = np.linalg.norm(vec[ax]) * c.n[ax]
    area = vol / length                                 # area perpendicular to the axis
    lam = prof * area                                   # e per unit length (e/bohr)
    dz = length / c.n[ax]
    z = np.arange(c.n[ax]) * dz
    dq = np.cumsum(lam) * dz
    print("axis %d: %d points, L = %.4f A, plane area %.4f A^2" % (args.axis, c.n[ax], length * to_a,
                                                                     area * to_a ** 2))
    print("total charge from profile %.5f e" % dq[-1])
    print("max |Delta Q(z)| = %.5f e at z = %.3f A" % (np.abs(dq).max(), z[np.argmax(np.abs(dq))] * to_a))
    if args.csv:
        np.savetxt(args.csv, np.column_stack([z * to_a, prof / to_a ** 3, lam / to_a, dq]),
                   delimiter=",", fmt="%.6e", header="z_A,rho_avg_e_per_A3,lambda_e_per_A,DeltaQ_e",
                   comments="")
        print("CSV written to %s" % args.csv)
    if args.output.lower() == "none" and not args.show:
        return
    import matplotlib
    if not args.show:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax1 = plt.subplots(figsize=(5.4, 3.4))
    ax1.plot(z * to_a, lam / to_a, color="#1f4e79", lw=1.1)
    ax1.axhline(0, color="0.5", lw=0.5)
    ax1.set_xlabel("z (A)")
    ax1.set_ylabel(r"$\lambda(z)$ (e/A)", color="#1f4e79")
    ax2 = ax1.twinx()
    ax2.plot(z * to_a, dq, color="#c0504d", lw=1.0, ls="--")
    ax2.set_ylabel(r"$\Delta Q(z)$ (e)", color="#c0504d")
    ax1.set_xlim(z[0] * to_a, z[-1] * to_a)
    fig.tight_layout()
    if args.output.lower() != "none":
        fig.savefig(args.output, dpi=args.dpi)
        print("figure written to %s" % args.output)
    if args.show:
        plt.show()


def main():
    ap = argparse.ArgumentParser(description="Cube file difference / planar average / info.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("info", help="grid, cell, range, integral")
    p.add_argument("cubes", nargs="+")
    p = sub.add_parser("diff", help="OUT = sum c_i * cube_i")
    p.add_argument("output", help="output cube")
    p.add_argument("inputs", nargs="+", help="input cubes (same grid)")
    p.add_argument("--coeffs", type=float, nargs="+", help="coefficients (default 1 -1 -1 ...)")
    p = sub.add_parser("planar", help="plane average along an axis and Delta Q(z)")
    p.add_argument("cube")
    p.add_argument("--axis", type=int, choices=[1, 2, 3], default=3)
    p.add_argument("--csv")
    p.add_argument("-o", "--output", default="planar.png", help="figure, 'none' = no figure")
    p.add_argument("--dpi", type=int, default=200)
    p.add_argument("--show", action="store_true")
    args = ap.parse_args()
    {"info": info, "diff": diff, "planar": planar}[args.cmd](args)


if __name__ == "__main__":
    main()
